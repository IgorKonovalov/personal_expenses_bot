// `pnpm build:widgets`: compiles each widget program under widgets/src/ (ADR-0053) into one HTML
// string and writes src/bot/widgets/programs.generated.ts, which is committed. A program is
// widgets/src/runtime.ts followed by the program's own file, transpiled, with imports and exports
// stripped, in one function scope. Lines are trimmed and blank lines dropped, so a widget source
// never holds a multi-line string or template literal. The output is deterministic:
// src/bot/widgets/programs.test.ts fails when the committed file differs from a fresh build.
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Every program, by the name the bot sends it under.
export const PROGRAMS = ['donut'] as const;
export type ProgramName = (typeof PROGRAMS)[number];

export const GENERATED_PATH = join(root, 'src/bot/widgets/programs.generated.ts');

function script(file: string): string {
  const source = readFileSync(join(root, 'widgets/src', file), 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      removeComments: true,
      verbatimModuleSyntax: true,
    },
  });
  return outputText
    .replace(/^import\b[\s\S]*?from\s*['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^export\s*\{\s*\};?\s*$/gm, '')
    .replace(/^export\s+/gm, '')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line !== '')
    .join('\n');
}

// A program's HTML: its script in the body, which it draws into.
export function programHtml(name: ProgramName): string {
  const js = `(()=>{\n${script('runtime.ts')}\n${script(`${name}.ts`)}\n})();`;
  if (js.includes('</script')) throw new Error(`widget ${name} holds </script`);
  return `<body><script>${js}</script></body>`;
}

// The generated module's text, formatted as the repo's prettier config formats it.
export async function generatedSource(): Promise<string> {
  const entries = PROGRAMS.map((name) => `  ${name}: ${JSON.stringify(programHtml(name))},`);
  const text = [
    '// Generated by scripts/build-widgets.ts from widgets/src/ (ADR-0053). Do not edit:',
    '// `pnpm build:widgets` rewrites it, and programs.test.ts fails when it is stale.',
    'export const WIDGET_PROGRAMS = {',
    ...entries,
    '} as const;',
    '',
    'export type WidgetProgram = keyof typeof WIDGET_PROGRAMS;',
    '',
  ].join('\n');
  const options = await prettier.resolveConfig(GENERATED_PATH);
  return prettier.format(text, { ...options, filepath: GENERATED_PATH });
}

// Run as a script, not when the test imports this module.
if (
  process.argv[1] !== undefined &&
  realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  writeFileSync(GENERATED_PATH, await generatedSource());
}
